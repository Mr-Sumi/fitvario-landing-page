// Reads src/content/blog/*.md and writes src/config/blog-pages.generated.ts so the page registry
// (sitemap, footer, breadcrumbs, seo-check) knows every post. Runs automatically before `npm run build`.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parseFrontmatter } from "../src/lib/frontmatter.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src", "content", "blog");
const MIN_POSTS_FOR_CATEGORY_PAGE = 5;
const PAGE_SIZE = 10;

const files = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".md")) : [];
const posts = files.map((f) => {
  const { data } = parseFrontmatter(readFileSync(join(dir, f), "utf8"));
  const slug = data.slug || f.replace(/\.md$/, "");
  for (const k of ["seoTitle", "title", "description", "updated", "published", "category"]) {
    if (!data[k]) throw new Error(`${f}: missing front-matter "${k}"`);
  }
  return { ...data, slug };
});

const q = (s) => JSON.stringify(String(s));
const entries = [];

// Blog index: always indexable once at least one post is public
const publicPosts = posts.filter((p) => !p.draft);
entries.push({
  path: "/blog",
  title: "Fitvario Blog: Practical Advice for Indian Gym Owners",
  description:
    "Practical guides for Indian gym owners on membership pricing, renewals, retention, lead follow-up and running a gym, with templates you can copy.",
  updated: posts.map((p) => p.updated).sort().at(-1) ?? "2026-10-11",
  navLabel: "Blog",
  draft: publicPosts.length === 0,
});

// Extra pages when there are more posts than fit one page
const pageCount = Math.max(1, Math.ceil(publicPosts.length / PAGE_SIZE));
for (let n = 2; n <= pageCount; n++) {
  entries.push({
    path: `/blog/page/${n}`,
    title: `Fitvario Blog: Practical Advice for Indian Gym Owners, Page ${n}`,
    description: `Page ${n} of the Fitvario blog: practical guides for Indian gym owners on pricing, renewals, retention and running a gym.`,
    updated: entries[0].updated,
    navLabel: `Blog, page ${n}`,
  });
}

for (const p of posts) {
  entries.push({
    path: `/blog/${p.slug}`,
    title: p.seoTitle,
    description: p.description,
    updated: p.updated,
    navLabel: p.title,
    draft: !!p.draft,
  });
}

// Category pages are noindex until a category holds enough public posts
const cats = new Map();
for (const p of publicPosts) cats.set(p.category, (cats.get(p.category) ?? 0) + 1);
for (const [name, count] of cats) {
  const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  entries.push({
    path: `/blog/category/${slug}`,
    title: `${name}: Fitvario Blog Posts for Gym Owners`,
    description: `Fitvario blog posts about ${name.toLowerCase()} for Indian gym owners: guides, scripts and checklists you can use in your gym.`,
    updated: entries[0].updated,
    navLabel: name,
    noindex: count < MIN_POSTS_FOR_CATEGORY_PAGE,
  });
}

const body = entries
  .map(
    (e) => `  {
    path: ${q(e.path)},
    kind: "blog",
    title: ${q(e.title)},
    description:
      ${q(e.description)},
    updated: ${q(e.updated)},
    navLabel: ${q(e.navLabel)},${e.draft ? "\n    draft: true," : ""}${e.noindex ? "\n    noindex: true," : ""}
  },`
  )
  .join("\n");

const out = `// GENERATED by scripts/gen-blog-registry.mjs from src/content/blog/*.md. Do not edit by hand.
import type { PageDef } from "./pages";

export const blogPages: PageDef[] = [
${body}
];

export const BLOG_PAGE_SIZE = ${PAGE_SIZE};
`;
writeFileSync(join(root, "src", "config", "blog-pages.generated.ts"), out);
console.log(`blog registry: ${posts.length} posts (${publicPosts.length} public), ${entries.length} pages`);
