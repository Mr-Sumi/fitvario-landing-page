// Merges search volumes from a Google Keyword Planner export into a ranked list.
// Put the export at docs/seo/keyword-planner.csv, then run:  node scripts/merge-volumes.mjs
// Output: docs/seo/keyword-volumes.md with every non-dropped keyword of the map, its volume, and a proposed
// top 10 of P1 keywords. The keyword map itself is never rewritten; review the proposal and edit by hand.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parseMap } from "./lib/keyword-map.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const csvPath = join(root, "docs", "seo", "keyword-planner.csv");
const mapPath = join(root, "docs", "seo", "keyword-map.md");

if (!existsSync(csvPath)) {
  console.log("No docs/seo/keyword-planner.csv yet.");
  console.log("Export it from Google Ads > Keyword Planner > Get search volume, then run this again.");
  process.exit(0);
}

// Keyword Planner exports are often UTF-16 tab-separated. Handle that and plain UTF-8 CSV.
let raw = readFileSync(csvPath);
let text = raw[0] === 0xff && raw[1] === 0xfe ? raw.toString("utf16le") : raw.toString("utf8");
text = text.replace(/^﻿/, "").replace(/\r\n/g, "\n");
const lines = text.split("\n").filter((l) => l.trim());
const delim = lines.some((l) => l.includes("\t")) ? "\t" : ",";
const split = (l) => l.split(delim).map((c) => c.replace(/^"|"$/g, "").trim());

const headerIdx = lines.findIndex((l) => /keyword/i.test(l) && /search/i.test(l));
if (headerIdx < 0) {
  console.error("Could not find a header row with Keyword and searches columns.");
  process.exit(1);
}
const header = split(lines[headerIdx]);
const kwCol = header.findIndex((h) => /^keyword$/i.test(h) || /keyword/i.test(h));
const volCol = header.findIndex((h) => /avg\.?\s*monthly\s*searches|monthly searches/i.test(h));
if (kwCol < 0 || volCol < 0) {
  console.error("Need columns named Keyword and Avg. monthly searches.");
  process.exit(1);
}

// "1K - 10K" style ranges: use the lower bound and flag them
function parseVolume(v) {
  const m = String(v).replace(/,/g, "").match(/(\d+(?:\.\d+)?)\s*([kKmM]?)/);
  if (!m) return null;
  const mult = /k/i.test(m[2]) ? 1000 : /m/i.test(m[2]) ? 1_000_000 : 1;
  return Math.round(Number(m[1]) * mult);
}
const volumes = new Map();
for (const l of lines.slice(headerIdx + 1)) {
  const c = split(l);
  const kw = (c[kwCol] ?? "").toLowerCase();
  const vol = parseVolume(c[volCol] ?? "");
  if (kw && vol !== null) volumes.set(kw, vol);
}

const entries = parseMap(readFileSync(mapPath, "utf8"));
const rows = [];
for (const e of entries) {
  for (const k of [e.primary, ...e.secondary].filter(Boolean)) {
    if (k.dropped) continue;
    rows.push({ keyword: k.text, page: e.path, priority: k.priority, volume: volumes.get(k.text.toLowerCase()) ?? null });
  }
}

const withVol = rows.filter((r) => r.volume !== null);
const missing = rows.filter((r) => r.volume === null);
const p1 = rows.filter((r) => r.priority === "P1").sort((a, b) => (b.volume ?? -1) - (a.volume ?? -1));

const md = `# Keyword volumes

Generated by scripts/merge-volumes.mjs from docs/seo/keyword-planner.csv. ${withVol.length} of ${rows.length} keywords matched.
Keyword Planner shows ranges for low-volume terms and may group close variants, so treat these as guidance, not truth.

## Proposed top 10 P1 keywords

${p1.slice(0, 10).map((r, i) => `${i + 1}. ${r.keyword} (${r.volume ?? "no data"}) on ${r.page}`).join("\n")}

The map currently has ${p1.length} P1 keywords. Consider demoting the rest to P2.

## All keywords with volume

| Keyword | Page | Priority | Monthly searches |
| --- | --- | --- | --- |
${withVol.sort((a, b) => b.volume - a.volume).map((r) => `| ${r.keyword} | ${r.page} | ${r.priority} | ${r.volume} |`).join("\n")}

## No volume found

${missing.map((r) => `- ${r.keyword} (${r.page})`).join("\n") || "None."}
`;
writeFileSync(join(root, "docs", "seo", "keyword-volumes.md"), md);
console.log(`wrote docs/seo/keyword-volumes.md (${withVol.length}/${rows.length} matched)`);
